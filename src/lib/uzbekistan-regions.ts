function normalizeAdministrativeLabel(value: string) {
  return value
    .toLowerCase()
    .replace(/[‘’`']/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function buildRegionAliases(region: string) {
  const trimmedRegion = region.trim();
  return Array.from(
    new Set([
      trimmedRegion,
      trimmedRegion.replace(/\s+viloyati$/i, '').trim(),
      trimmedRegion.replace(/\s+shahri$/i, '').trim(),
      trimmedRegion.replace(/\s+respublikasi$/i, '').trim(),
    ].filter(Boolean))
  );
}

function buildDistrictAliases(district: string) {
  const trimmedDistrict = district.trim();
  return Array.from(
    new Set([
      trimmedDistrict,
      trimmedDistrict.replace(/\s+tumani$/i, '').trim(),
    ].filter(Boolean))
  );
}

function labelMatchesText(label: string, text: string) {
  if (!label || !text) {
    return false;
  }

  const normalizedLabel = normalizeAdministrativeLabel(label);
  const normalizedText = normalizeAdministrativeLabel(text);
  return normalizedText.includes(normalizedLabel);
}

export function getDistrictsForRegion(region: string) {
  return UZBEKISTAN_REGION_OPTIONS.find((option) => option.name === region)?.districts || [];
}

export function buildLocationLabel(input: { region?: string; district?: string }) {
  return [input.region?.trim(), input.district?.trim()].filter(Boolean).join(', ');
}

export function buildFullAddress(input: {
  region?: string;
  district?: string;
  addressLine?: string;
}) {
  return [input.region?.trim(), input.district?.trim(), input.addressLine?.trim()].filter(Boolean).join(', ');
}

export function stripLocationPrefix(address: string, region?: string, district?: string) {
  const parts = address
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);
  const prefixes = [region?.trim(), district?.trim()].filter(Boolean) as string[];

  if (parts.length === 0 || prefixes.length === 0) {
    return address.trim();
  }

  let index = 0;
  while (
    index < prefixes.length &&
    index < parts.length &&
    normalizeAdministrativeLabel(parts[index]) === normalizeAdministrativeLabel(prefixes[index])
  ) {
    index += 1;
  }

  return (parts.slice(index).join(', ') || address).trim();
}

export function findRegionByText(text: string) {
  for (const option of UZBEKISTAN_REGION_OPTIONS) {
    if (buildRegionAliases(option.name).some((alias) => labelMatchesText(alias, text))) {
      return option.name;
    }
  }

  return '';
}

export function findDistrictByText(region: string, text: string) {
  const districts = getDistrictsForRegion(region);
  for (const district of districts) {
    if (buildDistrictAliases(district).some((alias) => labelMatchesText(alias, text))) {
      return district;
    }
  }

  return '';
}
